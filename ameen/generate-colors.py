# Generates ElementX/Sources/Ameen/AmeenColors.swift: the Compound semantic colours that use the
# green, gray, alpha gray or background palettes are replaced by the Ameen palette of the web app
# (ameen.css). High contrast keeps Element's values, as on the web app.
#
# Usage (from the repository root, after a build so that Swift packages are checked out):
#   python3 -I ameen/generate-colors.py <path to ameen.css> <path to compound-design-tokens/assets/ios/swift>

import json
import re
import sys
from pathlib import Path

CSS_PATH = Path(sys.argv[1])
TOKENS_PATH = Path(sys.argv[2])
OUTPUT_PATH = Path("ElementX/Sources/Ameen/AmeenColors.swift")

# Same choices as the web app (ameen.css): primary buttons and external links in Ameen green.
EXTRA_MAPPINGS = {
    "bgActionPrimaryRest": "green900",
    "bgActionPrimaryHovered": "green1000",
    "bgActionPrimaryPressed": "green1100",
    "textLinkExternal": "green900",
}
REPLACED_FAMILIES = re.compile(r"^(green|gray|alphaGray)\d+$|^themeBg$")


def css_palette(theme):
    css = CSS_PATH.read_text()
    block = re.search(r"\.cpd-theme-%s:not\(\[class\*=\"-hc\"\]\) \{(.*?)\}" % theme, css, re.S).group(1)
    palette = {}
    for name, value in re.findall(r"--cpd-color-([a-z0-9-]+):\s*([^;]+);", block):
        parts = name.split("-")
        key = parts[0] + "".join(p.capitalize() for p in parts[1:-1]) + parts[-1] if parts[-1].isdigit() else \
            parts[0] + "".join(p.capitalize() for p in parts[1:])
        palette[key] = value.strip()
    return palette


def rgba(value):
    if value.startswith("#"):
        return tuple(int(value[i:i + 2], 16) / 255 for i in (1, 3, 5)) + (1.0,)
    numbers = [float(n) for n in re.findall(r"[\d.]+", value)]
    return (numbers[0] / 255, numbers[1] / 255, numbers[2] / 255, numbers[3])


def high_contrast(core):
    contents = json.loads((TOKENS_PATH / "Colors.xcassets" / f"{core}.colorset" / "Contents.json").read_text())
    values = {}
    for entry in contents["colors"]:
        appearances = {a["appearance"]: a["value"] for a in entry.get("appearances", [])}
        if appearances.get("contrast") != "high":
            continue
        c = entry["color"]["components"]
        values["dark" if appearances.get("luminosity") == "dark" else "light"] = \
            tuple(float(c[k]) for k in ("red", "green", "blue", "alpha"))
    return values["light"], values["dark"]


def swift_color(rgba_value):
    return "UIColor(red: %.4f, green: %.4f, blue: %.4f, alpha: %.4f)" % rgba_value


def main():
    light, dark = css_palette("light"), css_palette("dark")
    semantic = dict(re.findall(r"public let (\w+) = CompoundCoreColorTokens\.(\w+)",
                               (TOKENS_PATH / "CompoundColorTokens.swift").read_text()))
    mappings = {token: core for token, core in semantic.items() if REPLACED_FAMILIES.match(core)}
    mappings.update(EXTRA_MAPPINGS)

    cores = sorted(set(mappings.values()))
    lines = [
        "//",
        "// Copyright 2026 Ameen.",
        "//",
        "// SPDX-License-Identifier: AGPL-3.0-only.",
        "// Please see LICENSE files in the repository root for full details.",
        "//",
        "",
        "// Generated by ameen/generate-colors.py from the web app palette (ameen.css). Do not edit.",
        "",
        "import Compound",
        "import SwiftUI",
        "",
        "/// Replaces the Compound colours with the Ameen palette (same as the web app).",
        "struct AmeenCompoundHook: CompoundHookProtocol {",
        "    func override(colors: CompoundColors, uiColors: CompoundUIColors) {",
    ]
    for token in sorted(mappings):
        core = mappings[token]
        lines.append(f"        colors.override(\\.{token}, with: Color(uiColor: AmeenPalette.{core}))")
        lines.append(f"        uiColors.override(\\.{token}, with: AmeenPalette.{core})")
    lines += ["    }", "}", "", "// swiftlint:disable line_length",
              "/// The Ameen palette. High contrast keeps Element's values.",
              "nonisolated enum AmeenPalette {"]
    for core in cores:
        hc_light, hc_dark = high_contrast(core)
        lines.append(f"    static let {core} = make(light: {swift_color(rgba(light[core]))}, "
                     f"dark: {swift_color(rgba(dark[core]))}, "
                     f"highContrastLight: {swift_color(hc_light)}, "
                     f"highContrastDark: {swift_color(hc_dark)})")
    lines += [
        "    ",
        "    private static func make(light: UIColor, dark: UIColor, highContrastLight: UIColor, highContrastDark: UIColor) -> UIColor {",
        "        UIColor { traits in",
        "            let isDark = traits.userInterfaceStyle == .dark",
        "            if traits.accessibilityContrast == .high {",
        "                return isDark ? highContrastDark : highContrastLight",
        "            }",
        "            return isDark ? dark : light",
        "        }",
        "    }",
        "}",
        "",
        "// swiftlint:enable line_length",
        "",
    ]
    OUTPUT_PATH.write_text("\n".join(lines))
    print(f"{len(mappings)} semantic colours, {len(cores)} palette colours -> {OUTPUT_PATH}")


main()
